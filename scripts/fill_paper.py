"""Fill the paper tables (tab:qor, tab:crossover) from the kept run records.

Emits the LaTeX row bodies and a short discussion paragraph to
docs/plan/paper-numbers.tex, so norns.tex can be updated without retyping numbers.

Conventions: geomean ratios are seeded / unseeded (below 1 better) over the designs where the
comparison exists; soft-full is the main soft arm, soft-inter is the inter-cluster-only row.
The k-means row pools the three k values, not all seven seed families. Crossover is reported as
the multiplier S of VPR's automatic start temperature; retention is at the hot step (2 x S), per
seed family, median over designs. Sweep results are read from the committed copies in
data/<design>/crossover/ (runs/ is not committed).

Usage: python scripts/fill_paper.py
"""

from __future__ import annotations

import statistics
import sys

import nornlib as nl
import report

ROWS = (("urd", "Urd (hierarchy)", "Urd (hierarchy)"),
        ("louvain", "Louvain", "Louvain"),
        ("spectral", "Spectral", "Spectral"),
        ("affinity", "Affinity propagation", "Affinity propagation"),
        ("kmeans", "k-means ($k$, $2k$, $4k$)", "k-means"))
# The k-means row pools the three k values, not all seven seed families.
KMEANS = ("kmeans_k", "kmeans_2k", "kmeans_4k")


def latex_design(name: str) -> str:
    """Design names carry underscores; escape them for text mode."""
    return name.replace("_", r"\_")


def benchmark_block() -> tuple[list[str], dict[str, object] | None]:
    """tab:benchmarks rows and their statistics from the committed size extraction."""
    path = nl.DATA / "benchmark-sizes.json"
    if not path.is_file():
        return [], None
    sizes = nl.read_json(path)
    entries = sizes.get("designs", {})
    suite = str(sizes.get("suite", "VTR 8.0"))
    rows: list[str] = []
    clbs: list[int] = []
    sides: list[int] = []
    tiles: list[int] = []
    by_design: dict[str, int] = {}
    for design in nl.DESIGN_ORDER:
        entry = entries.get(design)
        if entry is None:
            continue
        info = nl.DATA / design / "netlist.json"
        modules = nl.read_json(info).get("modules") if info.is_file() else "--"
        gx, gy = entry["grid"]
        clb = int(entry["clbs"])
        clbs.append(clb)
        sides.append(int(gx))
        tiles.append(int(entry["tiles"]))
        by_design[design] = clb
        rows.append(f"{latex_design(design)} & {entry.get('suite', suite)} & {modules} & {clb} "
                    f"& {entry['memory']} & {entry['mult_36']} & ${gx}\\times${gy} "
                    f"({entry['tiles']}) \\\\")
    if not rows:
        return [], None
    stats = {
        "n": len(rows),
        "clb_mean": round(statistics.mean(clbs), 1),
        "clb_median": statistics.median(clbs),
        "clb_total": sum(clbs),
        "grid_mean": round(statistics.mean(sides), 1),
        "grid_median": statistics.median(sides),
        "tiles_mean": round(statistics.mean(tiles), 1),
        "tiles_median": statistics.median(tiles),
        "clb_min": min(clbs),
        "clb_max": max(clbs),
        "smallest": min(by_design, key=lambda d: by_design[d]),
        "largest": max(by_design, key=lambda d: by_design[d]),
    }
    return rows, stats



def main(argv: list[str]) -> int:
    data, designs = report.load_all()
    out = ["% Generated by scripts/fill_paper.py from data/<design>/runs.jsonl", ""]
    # tab:qor rows (soft-full; the inter-cluster-only row is soft-inter of all families)
    out.append("% tab:qor rows")
    for fam, label, _ in ROWS:
        cols = []
        for metric in report.METRICS:
            values = []
            for design in designs:
                base = report.pick(data[design], "baseline")
                seeds = KMEANS if fam == "kmeans" else (fam,)
                for seed in seeds:
                    run = report.pick(data[design], "soft", seed, "full")
                    r = report.ratio(run, base, metric)
                    if r is not None:
                        values.append(r)
            cols.append(nl.geomean(values))
        out.append(f"{label} & {nl.fmt(cols[0])} & {nl.fmt(cols[1])} & {nl.fmt(cols[2])} & "
                   f"{nl.fmt(cols[3])} \\\\")
    cols = []
    for metric in report.METRICS:
        values = []
        for design in designs:
            base = report.pick(data[design], "baseline")
            for seed in report.FAMILIES:
                run = report.pick(data[design], "soft", seed, "inter")
                r = report.ratio(run, base, metric)
                if r is not None:
                    values.append(r)
        cols.append(nl.geomean(values))
    out.append(f"Inter-cluster only & {nl.fmt(cols[0])} & {nl.fmt(cols[1])} & {nl.fmt(cols[2])} "
               f"& {nl.fmt(cols[3])} \\\\")
    # hard arm for the discussion
    out += ["", "% hard arm geomeans (discussion)"]
    values = {m: [] for m in report.METRICS}
    hard_by_design = {}
    hard_by_family = {f: [] for f in report.FAMILIES}
    n_hard = 0
    n_hard_better = 0
    for design in designs:
        base = report.pick(data[design], "baseline")
        per_design = []
        for seed in report.FAMILIES:
            run = report.pick(data[design], "hard", seed)
            if run is None:
                continue
            n_hard += 1
            for m in report.METRICS:
                r = report.ratio(run, base, m)
                if r is not None:
                    values[m].append(r)
            wl = report.ratio(run, base, "wirelength")
            if wl is not None:
                per_design.append(wl)
                hard_by_family[seed].append(wl)
                if wl < 1:
                    n_hard_better += 1
        if per_design:
            hard_by_design[design] = nl.fmt(nl.geomean(per_design))
    out.append("% hard " + " ".join(f"{m}={nl.fmt(nl.geomean(values[m]))}"
                                    for m in report.METRICS))
    out.append(f"% hard runs {n_hard}, {n_hard_better} better than baseline; per design "
               + " ".join(f"{d}={v}" for d, v in hard_by_design.items()))
    # tab:crossover rows
    out += ["", "% tab:crossover rows"]
    for fam, label, _ in ROWS:
        scales = []
        temps = []
        rets = []
        for design in designs:
            path = nl.data_crossover(design, "crossover.json")
            if not path.is_file():
                continue
            res = nl.read_json(path)
            scale = res.get("crossover_scale")
            if scale is None:
                continue
            seeds = KMEANS if fam == "kmeans" else (fam,)
            for seed in seeds:
                hot = report.pick(data[design], "hot", seed)
                cold = report.pick(data[design], "cold", scale=float(scale))
                if hot is None or cold is None:
                    continue
                scales.append(float(scale))
                # init_t is already the scaled VPR start temperature; do not scale it again.
                temps.append(float(cold.get("init_t") or 0))
                if hot.get("retention") is not None:
                    rets.append(float(hot["retention"]))
        if scales:
            temps = [t for t in temps if t > 0]
            tcol = f"{statistics.median(temps):.4g}" if temps else "--"
            out.append(f"% T median {tcol} (cost-normalized units) "
                       f"for {label}")
            out.append(f"{label} & {statistics.median(scales):g}$\\times$ & "
                       f"{statistics.median(rets):.3f} \\\\")
        else:
            out.append(f"{label} & -- & -- \\\\")
    # tab:benchmarks rows and their size statistics
    bench_rows, bench_stats = benchmark_block()
    out += ["", "% tab:benchmarks rows"]
    out += bench_rows
    if bench_stats is not None:
        out.append(f"% benchmark sizes: n={bench_stats['n']} "
                   f"CLB mean={bench_stats['clb_mean']} median={bench_stats['clb_median']} "
                   f"grid mean={bench_stats['grid_mean']} median={bench_stats['grid_median']} "
                   f"tiles mean={bench_stats['tiles_mean']} "
                   f"median={bench_stats['tiles_median']}")
    out += ["", "% discussion medians"]
    soft_vals = []
    inter_vals = []
    hard_vals = []
    chan_soft = []
    run_soft = []
    for design in designs:
        base = report.pick(data[design], "baseline")
        for seed in report.FAMILIES:
            run = report.pick(data[design], "soft", seed, "full")
            for target, metric in ((soft_vals, "wirelength"),):
                r = report.ratio(run, base, metric)
                if r is not None:
                    target.append(r)
            for target, metric in ((chan_soft, "chan_width"), (run_soft, "place_s")):
                r = report.ratio(run, base, metric)
                if r is not None:
                    target.append(r)
            r = report.ratio(report.pick(data[design], "soft", seed, "inter"), base, "wirelength")
            if r is not None:
                inter_vals.append(r)
            r = report.ratio(report.pick(data[design], "hard", seed), base, "wirelength")
            if r is not None:
                hard_vals.append(r)
    def g(v):
        return nl.fmt(nl.geomean(v))
    out.append(f"% soft-full WL={g(soft_vals)} inter WL={g(inter_vals)} hard WL={g(hard_vals)} "
               f"soft chan={g(chan_soft)} soft runtime={g(run_soft)}")
    ons = []
    offs = []
    for design in designs:
        on = nl.data_crossover(design, "crossover.json")
        off = nl.data_crossover(design, "checkpoint.json")
        if on.is_file() and nl.read_json(on).get("crossover_scale") is not None:
            ons.append(float(nl.read_json(on)["crossover_scale"]))
        if off.is_file() and nl.read_json(off).get("crossover_scale_off") is not None:
            offs.append(float(nl.read_json(off)["crossover_scale_off"]))
    if ons:
        out.append(f"% crossover scale median on={statistics.median(ons):g}")
    if offs:
        out.append(f"% crossover scale median off={statistics.median(offs):g}")
    out += ["", "% checkpointing (discussion): crossover scale per design"]
    for design in designs:
        on = nl.data_crossover(design, "crossover.json")
        off = nl.data_crossover(design, "checkpoint.json")
        if on.is_file() and off.is_file():
            out.append(f"% {design}: on={nl.read_json(on).get('crossover_scale')} "
                       f"off={nl.read_json(off).get('crossover_scale_off')}")
    path = nl.WS / "docs" / "plan" / "paper-numbers.tex"
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    summary = {
        "soft_wl": g(soft_vals), "inter_wl": g(inter_vals), "hard_wl": g(hard_vals),
        "soft_chan": g(chan_soft), "soft_runtime": g(run_soft),
        "crossover_on_median": statistics.median(ons) if ons else None,
        "crossover_off_median": statistics.median(offs) if offs else None,
        "hard_runs": n_hard, "hard_runs_better": n_hard_better,
        "hard_design_wl": hard_by_design,
        "hard_family_wl": {f: nl.fmt(nl.geomean(v)) for f, v in hard_by_family.items() if v},
        "benchmarks": bench_stats,
    }
    hot = {}
    wins = {}
    for seed in report.FAMILIES:
        rets = []
        won = 0
        n = 0
        for design in designs:
            h = report.pick(data[design], "hot", seed)
            if h is None or h.get("scale") is None:
                continue
            if h.get("retention") is not None:
                rets.append(float(h["retention"]))
            u = report.pick(data[design], "unseeded", scale=float(h["scale"]))
            if u and h.get("wirelength") and u.get("wirelength"):
                n += 1
                won += 1 if float(h["wirelength"]) < float(u["wirelength"]) else 0
        hot[seed] = round(statistics.median(rets), 3) if rets else None
        wins[seed] = [won, n]
    summary["hot_retention"] = hot
    summary["hot_wins"] = wins
    hot_all = [float(h["retention"]) for seed in report.FAMILIES for design in designs
               for h in [report.pick(data[design], "hot", seed)]
               if h is not None and h.get("retention") is not None]
    summary["hot_retention_range"] = ([round(min(hot_all), 3), round(max(hot_all), 3)]
                                      if hot_all else None)
    nl.write_json(nl.WS / "docs" / "plan" / "paper-summary.json", summary)
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
